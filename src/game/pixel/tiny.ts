/** Draws `text` in the tiny face, `scale` times as big. Returns its width. */
export function drawTiny(r: Raster, text: string, x: number, y: number, color: string, scale = 1): number {
  let cx = x
  for (const ch of text.toUpperCase()) {
    const rows = TINY[ch] ?? DIGITS[ch]
    if (rows) {
      rows.forEach((row, gy) => {
        for (let gx = 0; gx < 3; gx++) if (row[gx] === '#') r.rect(cx + gx * scale, y + gy * scale, scale, scale, color)
      })
    }
    cx += 4 * scale
  }
  return cx - x
}

/** How wide `text` is in the tiny face at `scale`. */
export function tinyWidth(text: string, scale = 1): number {
  return text.length * 4 * scale - scale
}
